
#pragma once

#include <cmath>
#include <string>

/**
 * @brief Абстрактный базовый класс математической модели.
 *
 * Класс Model задаёт общий интерфейс для всех математических
 * моделей объекта управления.
 *
 * Благодаря механизму полиморфизма с объектами разных моделей
 * можно работать через общий указатель или ссылку типа Model.
 */
class Model
{
public:

    /**
     * @brief Вычисляет следующее состояние объекта.
     *
     * @param y Текущее значение выходной переменной.
     * @param u Управляющее воздействие.
     * @param dt Шаг дискретизации по времени.
     * @return Новое значение выходной переменной.
     */
    virtual double calculateNext(double y, double u, double dt) = 0;

    /**
     * @brief Возвращает название математической модели.
     *
     * @return Строка с названием модели.
     */
    virtual string getName() const = 0;

    /**
     * @brief Сбрасывает внутреннее состояние модели.
     *
     * Используется перед началом нового эксперимента,
     * чтобы предыдущие вычисления не влияли на результат.
     */
    virtual void reset() = 0;

    /**
     * @brief Виртуальный деструктор базового класса.
     *
     * Обеспечивает корректное удаление объектов производных
     * классов через указатель на базовый класс Model.
     */
    virtual ~Model() = default;
};


/**
 * @brief Математическая модель 1.10.
 *
 * Модель описывается разностным уравнением:
 *
 * y(t+1) = a1*y(t) + b1*u(t) + b2*u(t-2)
 *
 * В модели учитывается текущее управляющее воздействие
 * и запаздывающее воздействие с двумя шагами задержки.
 */
class Model1_10 : public Model
{
private:

    double m_a1;
    double m_b1;
    double m_b2;

    // Предыдущие значения управляющего воздействия.
    double m_u_t_minus_1 = 0.0;
    double m_u_t_minus_2 = 0.0;

public:

    /**
     * @brief Конструктор модели 1.10.
     *
     * @param a1 Коэффициент при текущем значении y.
     * @param b1 Коэффициент при текущем управляющем воздействии.
     * @param b2 Коэффициент при воздействии с задержкой.
     */
    Model1_10(double a1, double b1, double b2)
        : m_a1(a1), m_b1(b1), m_b2(b2)
    {}

    /**
     * @brief Вычисляет следующее значение выходной переменной.
     *
     * @param y Текущее состояние модели.
     * @param u Текущее управляющее воздействие.
     * @param dt Шаг времени (в данной модели не используется).
     * @return Рассчитанное следующее значение y.
     */
    double calculateNext(double y, double u, double dt) override
    {
        (void)dt;

        double nextY = m_a1 * y
            + m_b1 * u
            + m_b2 * m_u_t_minus_2;

        // Обновление истории управляющих воздействий.
        m_u_t_minus_2 = m_u_t_minus_1;
        m_u_t_minus_1 = u;

        return nextY;
    }

    /**
     * @brief Возвращает название модели.
     *
     * @return Название Model 1.10.
     */
    string getName() const override
    {
        return "Model 1.10 - Distributed Control Window Model";
    }

    /**
     * @brief Сбрасывает историю управляющих воздействий.
     *
     * Обнуляет значения u(t-1) и u(t-2).
     */
    void reset() override
    {
        m_u_t_minus_1 = 0.0;
        m_u_t_minus_2 = 0.0;
    }
};


/**
 * @brief Математическая модель 2.4.
 *
 * Модель описывается нелинейным выражением:
 *
 * y(t+1) = a*y(t)*cos(y(t)) + b*ln(1 + |u(t)|)
 *
 * В модели присутствуют тригонометрическая и логарифмическая
 * зависимости, поэтому она относится к классу нелинейных систем.
 */
class Model2_4 : public Model
{
private:

    double m_a;
    double m_b;

public:

    /**
     * @brief Конструктор модели 2.4.
     *
     * @param a Коэффициент нелинейной зависимости выходной переменной.
     * @param b Коэффициент влияния управляющего воздействия.
     */
    Model2_4(double a, double b)
        : m_a(a), m_b(b)
    {}

    /**
     * @brief Вычисляет следующее значение выходной переменной.
     *
     * @param y Текущее состояние модели.
     * @param u Управляющее воздействие.
     * @param dt Шаг времени (в данной модели не используется).
     * @return Рассчитанное следующее значение y.
     */
    double calculateNext(double y, double u, double dt) override
    {
        (void)dt;

        return m_a * y * cos(y)
            + m_b * log(1.0 + fabs(u));
    }

    /**
     * @brief Возвращает название модели.
     *
     * @return Название Model 2.4.
     */
    string getName() const override
    {
        return "Model 2.4 - Logarithmic Multi-Variable Interaction";
    }

    /**
     * @brief Сбрасывает внутреннее состояние модели.
     *
     * Модель не хранит историю предыдущих управляющих воздействий,
     * поэтому дополнительная инициализация не требуется.
     */
    void reset() override
    {
        // Сброс не требуется, так как внутреннее состояние не накапливается
    }
};


/**
 * @brief Математическая модель 3.8.
 *
 * Модель описывается дифференциальным уравнением:
 *
 * dy/dt = -a1*y - a2*y^2 + b*u
 *
 * Для численного решения используется явный метод Эйлера:
 *
 * y(t+1) = y(t) + dt * (-a1*y - a2*y^2 + b*u)
 */
class Model3_8 : public Model
{
private:

    double m_a1;
    double m_a2;
    double m_b;

public:

    /**
     * @brief Конструктор модели 3.8.
     *
     * @param a1 Коэффициент линейной составляющей.
     * @param a2 Коэффициент квадратичной составляющей.
     * @param b Коэффициент управляющего воздействия.
     */
    Model3_8(double a1, double a2, double b)
        : m_a1(a1), m_a2(a2), m_b(b)
    {}

    /**
     * @brief Вычисляет следующее состояние модели методом Эйлера.
     *
     * @param y Текущее значение выходной переменной.
     * @param u Управляющее воздействие.
     * @param dt Шаг дискретизации по времени.
     * @return Приближённое значение y на следующем шаге.
     */
    double calculateNext(double y, double u, double dt) override
    {
        double dydt = -m_a1 * y
            - m_a2 * y * y
            + m_b * u;

        return y + dt * dydt;
    }

    /**
     * @brief Возвращает название модели.
     *
     * @return Название Model 3.8.
     */
    string getName() const override
    {
        return "Model 3.8 - Combined Linear-Quadratic Decay";
    }

    /**
     * @brief Сбрасывает внутреннее состояние модели.
     *
     * Модель не хранит дополнительные переменные состояния,
     * поэтому отдельный сброс не требуется.
     */
    void reset() override
    {
        // Сброс не требуется, так как внутреннее состояние не накапливается
    }
};
